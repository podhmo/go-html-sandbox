#!/bin/sh
# embed.sh writes OUT, a MoonBit source holding every *.md file directly in
# DIR as `files`, an array of (file name, content) pairs sorted by name, the
# way go:embed gives the Go blog its posts.
#
#   sh scripts/embed.sh posts/embedded.mbt ../go/examples/blog/posts
#
# moon runs it before building through dev_build in posts/moon.pkg, and the
# Makefile runs it too: moon reruns it only when DIR itself changes (a file
# added or removed), not when a file in it is edited. OUT is rewritten only
# when its content changes, so running it again rebuilds nothing.
set -eu

out=$1
# moon passes DIR as ./DIR; drop that so both callers write the same file.
dir=${2#./}
tmp=$out.tmp
trap 'rm -f "$tmp" "$tmp.one"' EXIT

LC_ALL=C
export LC_ALL

{
  echo "// Code generated by scripts/embed.sh from $dir; DO NOT EDIT."
  i=0
  for f in "$dir"/*.md; do
    [ -f "$f" ] || continue
    # moon tool embed is what moon.pkg's :embed runs; drop its header.
    moon tool embed --text -i "$f" -o "$tmp.one" --name "file_$i"
    echo
    sed -n '/^\/\/\/|$/,$p' "$tmp.one"
    i=$((i + 1))
  done
  echo
  echo '///|'
  echo "/// files holds every *.md file in $dir as pairs of"
  echo '/// the file name and its content, sorted by name.'
  echo 'pub let files : ReadOnlyArray[(String, String)] = ['
  i=0
  for f in "$dir"/*.md; do
    [ -f "$f" ] || continue
    echo "  (\"${f##*/}\", file_$i),"
    i=$((i + 1))
  done
  echo ']'
} >"$tmp"

if cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
