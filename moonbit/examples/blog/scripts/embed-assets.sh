#!/bin/sh
# embed-assets.sh writes OUT, a MoonBit source holding the Go blog's
# site.css and favicon.svg from DIR, with the version the pages put in the
# stylesheet's URL: the first 4 bytes of its SHA-256 in hex, as the Go
# blog's siteCSSPath has it.
#
#   sh examples/blog/scripts/embed-assets.sh examples/blog/assets/embedded.mbt ../go/examples/blog/internal/site
#
# Like embed.sh, moon runs it through dev_build in assets/moon.pkg and the
# Makefile runs it too, and OUT is rewritten only when its content changes.
set -eu

out=$1
# moon passes DIR as ./DIR; drop that so both callers write the same file.
dir=${2#./}
tmp=$out.tmp
trap 'rm -f "$tmp" "$tmp.one"' EXIT

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1"
  else
    shasum -a 256 "$1"
  fi | cut -c1-8
}

# embed NAME FILE writes FILE as `pub let NAME : String`, with moon tool
# embed (what moon.pkg's :embed runs) minus its header.
embed() {
  moon tool embed --text -i "$2" -o "$tmp.one" --name "$1"
  echo
  sed -n '/^\/\/\/|$/,$p' "$tmp.one" | sed 's/^let /pub let /'
}

{
  echo "// Code generated by scripts/embed-assets.sh from $dir; DO NOT EDIT."
  embed site_css "$dir/site.css"
  embed favicon_svg "$dir/favicon.svg"
  echo
  echo '///|'
  echo '/// site_css_version is the first 4 bytes of the SHA-256 of site_css in hex.'
  echo "pub let site_css_version : String = \"$(sha256 "$dir/site.css")\""
} >"$tmp"

if cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
